from google import genai

client = genai.Client()

# 対象のサッカー記事
article = """
プレミアリーグ第5節、アーセナル対マンチェスター・シティの試合は2-2の引き分けに終わった。前半9分にシティのハーランドが先制点を奪うも、22分にアーセナルのカラフィオーリが同点弾、さらに前半ATにマガリャンイスがヘディングで逆転。しかし前半終了間際にトロサールが退場となり、後半はシティが猛攻。後半AT8分、ストーンズの劇的な同点弾で幕を閉じた。シュート数はシティ33本、アーセナル5本と圧倒的な攻撃と守備のぶつかり合いだった。
"""

# レベル1：雑な指示（普通のチャット風）
p1 = f"以下の文章を要約してください。\n\n{article}"

# レベル2：役割（アナリスト）＋ 形式の指定（箇条書き）
p2 = f"""あなたはプロのサッカーアナリストです。以下の文章を分析し、指定のフォーマットで出力してください。

【フォーマット】
- 対戦カードと最終スコア：
- 得点者一覧（チーム別）：
- 試合の決定的なターニングポイント（1文）：
- 特筆すべきスタッツ：

【対象文章】
{article}"""

# レベル3：レベル2 ＋ 少数例（Few-shot手本）＋ 厳格な制約（プログラム連携用）
p3 = f"""あなたはサッカーデータ分析システムのデータ抽出エンジンです。
以下の【ルール】と【手本】を厳格に守り、対象テキストからデータのみを抽出してください。

【ルール】
- 挨拶や前置き（「承知しました」等）は一切出力せず、指定フォーマットのみ出力すること。
- 事実情報のみを抽出し、主観的な感想は含めないこと。

【手本】
入力: リヴァプール対チェルシーは2-1でリヴァプール勝利。サラーとジョーンズが得点、チェルシーはジャクソン。
出力:
MATCH: リヴァプール vs チェルシー (2-1)
SCORERS_HOME: サラー, ジョーンズ
SCORERS_AWAY: ジャクソン
RED_CARDS: なし

【対象文章】
{article}"""

# 3つを順番に実行して画面に表示！
for level_name, prompt in [("レベル1：雑な指示", p1), ("レベル2：役割＋形式指定", p2), ("レベル3：手本＋制約付き", p3)]:
    print(f"\n{'='*20} {level_name} {'='*20}")
    response = client.models.generate_content(
        model="gemini-3.6-flash",
        contents=prompt
    )
    print(response.text.strip())